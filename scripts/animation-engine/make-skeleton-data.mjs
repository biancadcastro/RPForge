// Offline generator for src/animation-engine/freemode-skeletons.js.
// Usage: node scripts/animation-engine/make-skeleton-data.mjs <mp_m_freemode_01.skel> <mp_f_freemode_01.skel>
// Reads two openFormats `.skel` files (read-only) and writes the compact reference data
// the FBX converter needs to work with zero setup: bone name, tag, parent, rest rotation
// and rest offset. Nothing else of the source files is kept.
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {parseSkel} from '../../src/animation-engine/skeleton.js';

const [male, female] = process.argv.slice(2);
if (!male || !female) { console.error('usage: make-skeleton-data.mjs <male.skel> <female.skel>'); process.exit(2); }
const n = v => { const s = String(+v.toFixed(8)); return s === '-0' ? '0' : s; };
const pack = path => parseSkel(readFileSync(path, 'utf8')).bones
  .map(b => `  ['${b.name}',${b.tag},${b.parent},${[...b.rotation, ...b.translation].map(n).join(',')}],`).join('\n');
const out = `// GENERATED by scripts/animation-engine/make-skeleton-data.mjs - do not edit by hand.
// Reference skeletons of the GTA V freemode peds (bone name, tag, parent index, rest
// rotation x,y,z,w and rest offset x,y,z in metres, local to the parent). A YCD stores
// only bone tags, so the FBX converter needs this data to work without any setup.
export const FREEMODE_MALE = [
${pack(male)}
];
export const FREEMODE_FEMALE = [
${pack(female)}
];
`;
writeFileSync(fileURLToPath(new URL('../../src/animation-engine/freemode-skeletons.js', import.meta.url)), out);
console.log('written', out.length, 'bytes');
